import hashlib,json,pathlib,subprocess,tempfile,sys
sys.path.insert(0,'scripts')
from audit_std_borrow_ref_new_llbc import inspect,negative_controls
root=pathlib.Path.cwd(); profile=json.load(open('proofs/extraction/tool-patches/std-borrow-ref-new-profile.json'))
for mapping in [profile['sha256'],profile['base_source_sha256']]:
 for f,h in mapping.items(): assert hashlib.sha256(pathlib.Path(f).read_bytes()).hexdigest()==h,f
with tempfile.TemporaryDirectory(prefix='kasane-std-borrow-ref-new-') as tmp:
 tmp=pathlib.Path(tmp)
 for label,transparent in [('opaque_cell',False),('transparent_cell',True)]:
  dest=tmp/(label+'.llbc'); out=tmp/label;out.mkdir()
  args=['.local/proof-tools/charon-gat-candidate/charon','cargo','--preset=aeneas','--mir','promoted','--error-on-warnings','--start-from','core::cell::BorrowRef::new','--include','core::cell::_::new','--include','core::cell::BorrowRef','--include','core::cell::is_reading','--include','core::cell::UNUSED']
  if transparent:
   for name in ['core::cell::_::get','core::cell::_::replace','core::cell::Cell','core::cell::UnsafeCell']: args+=['--include',name]
  args+=['--dest-file',str(dest),'--','--manifest-path','crates/evm-core/Cargo.toml','--lib','--locked']
  r=subprocess.run(args,capture_output=True,text=True,timeout=180);assert r.returncode==0,r.stdout+r.stderr
  data=json.loads(dest.read_text());assert inspect(data,transparent)==profile['observations'][label];negative_controls(data,transparent)
