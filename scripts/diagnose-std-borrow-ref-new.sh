  for mode,args in [('borrow',['-borrow-check']),('lean',['-backend','lean','-dest',str(out),'-namespace','StdBorrowRefNew','-use-lean-modules','false'])]:
   r=subprocess.run([tool]+args+['-abort-on-error','-warnings-as-errors',str(dest)],capture_output=True,text=True,timeout=180)
   if transparent:
    assert r.returncode!=0 and 'Aeneas does not yet support dereferencing raw pointers.' in r.stdout+r.stderr,r.stdout+r.stderr
    assert not list(out.rglob('*.lean')),'Unaccepted partial Lean output'
    print(label+' '+mode+' rejects actual raw-pointer dereference')
   else:
    assert r.returncode==0,r.stdout+r.stderr
    print(label+' '+mode+' passed with Cell operations remaining unproved')
  if not transparent:
   assert len(list(out.rglob('*.lean')))==1
   source=(out/'OpaqueCell.lean').read_text()
   assert source==(root/'proofs/extraction/quarantine/std-borrow-ref-new/New.lean').read_text(),'Quarantined generated bytes changed'
   # First compile the unchanged generator output. Then reject its unresolved axioms.
   lean_root=root/'proofs/extraction/u256-lean'
   with tempfile.TemporaryDirectory(prefix='borrow-ref-axiom-',dir=lean_root/'.lake') as lean_tmp:
